// ============================================================
// 1. function 宣言
// ============================================================
function add(a, b) {
    return a + b;
}


// ============================================================
// 2. アロー関数（このカリキュラムで多用する書き方）
// ============================================================
const addArrow = (a, b) => {
    return a + b;
};

// 処理が1行だけなら {} と return を省略できる
const addShort = (a, b) => a + b;

console.log(add(1, 2), addArrow(1, 2), addShort(1, 2));   // 3 3 3


// ============================================================
// 3. 関数の中で文字列を作って返す
// ============================================================
const greet = (name) => `こんにちは、${name}さん`;
console.log(greet('山田'));   // こんにちは、山田さん


// ============================================================
// 4. return が無い関数は undefined を返す
// ============================================================
const noReturn = (a) => {
    a + 1;   // 計算はするが、結果を返していない
};
console.log(noReturn(1));   // undefined
